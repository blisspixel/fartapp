func TestCoverageRejectsNonfiniteAndOutOfRangeMinima(t *testing.T) {
	for _, value := range []float64{math.NaN(), math.Inf(1), math.Inf(-1), -1, 100.1} {
		for _, options := range []coverageOptions{{aggregate: value}, {pkg: value}} {
			if _, err := CheckCoverage(t.TempDir(), options); err == nil || !strings.Contains(err.Error(), "finite numbers between 0 and 100") {
				t.Fatalf("minima %#v: %v", options, err)
			}
		}
	}
}

func TestCoverageRejectsAmbiguousOverflowingAndEmptyAccounting(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "go.mod"), "module example.com/lab\n")
	writeFile(t, filepath.Join(root, "alpha.go"), "package alpha\n")
	for name, profile := range map[string]string{
		"unknown mode":     "mode: surprise\nexample.com/lab/alpha.go:1.1,2.2 1 1\n",
		"mode only":        "mode: count\n",
		"zero statements":  "mode: set\nexample.com/lab/alpha.go:1.1,2.2 0 1\n",
		"count overflow":   "mode: count\nexample.com/lab/alpha.go:1.1,2.2 1 9223372036854775808\n",
		"block overflow":   "mode: count\nexample.com/lab/alpha.go:1.1,2.2 9223372036854775808 1\n",
		"total overflow":   "mode: count\nexample.com/lab/alpha.go:1.1,2.2 9223372036854775807 1\nexample.com/lab/alpha.go:3.1,4.2 1 1\n",
		"set count":        "mode: set\nexample.com/lab/alpha.go:1.1,2.2 1 2\n",
		"zero coordinate":  "mode: set\nexample.com/lab/alpha.go:0.1,2.2 1 1\n",
		"reversed lines":   "mode: set\nexample.com/lab/alpha.go:2.1,1.2 1 1\n",
		"reversed columns": "mode: set\nexample.com/lab/alpha.go:1.2,1.1 1 1\n",
		"duplicate block":  "mode: set\nexample.com/lab/alpha.go:1.1,2.2 1 1\nexample.com/lab/alpha.go:1.1,2.2 1 1\n",
		"source traversal": "mode: set\nexample.com/lab/../outside.go:1.1,2.2 1 1\n",
		"source alias":     "mode: set\nexample.com/lab/./alpha.go:1.1,2.2 1 1\n",
		"source backslash": "mode: set\nexample.com/lab/sub\\alpha.go:1.1,2.2 1 1\n",
	} {
		t.Run(name, func(t *testing.T) {
			writeFile(t, filepath.Join(root, "coverage.out"), profile)
			if _, err := CheckCoverage(root, coverageOptions{profile: "coverage.out"}); err == nil {
				t.Fatal("invalid profile accepted")
			}
		})
	}
}

func TestCoverageGeneratedMarkerFollowsGoSemantics(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "go.mod"), "module\t\"example.com/lab\" // module identity\n")
	writeFile(t, filepath.Join(root, "normal.go"), "package normal\n// Code generated by a test tool. DO NOT EDIT.\n")
	writeFile(t, filepath.Join(root, "generated.go"), "// License header\n\n\n\n\n\n// Code generated by a test tool. DO NOT EDIT.\npackage normal\n")
	writeFile(t, filepath.Join(root, "coverage.out"), "mode: atomic\nexample.com/lab/normal.go:1.1,2.2 2 3\nexample.com/lab/generated.go:1.1,2.2 100 0\n")
	result, err := CheckCoverage(root, coverageOptions{profile: "coverage.out", aggregate: 100, pkg: 100})
	if err != nil || len(result.Failures) != 0 || !strings.Contains(result.Report, "100.0% (2/2)") {
		t.Fatalf("generated marker accounting = %#v, %v", result, err)
	}
}

func TestContainedPathResolvesMissingLeavesAndRejectsSymlinkEscapes(t *testing.T) {
	root := t.TempDir()
	outside := t.TempDir()
	if relative, err := containedPath(root, filepath.Join(root, "absent", "nested", "file.md")); err != nil || relative != "absent/nested/file.md" {
		t.Fatalf("missing contained leaf = %q, %v", relative, err)
	}
	link := filepath.Join(root, "linked")
	if err := os.Symlink(outside, link); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	if _, err := containedPath(root, filepath.Join(link, "missing.md")); !errors.Is(err, ErrPathEscape) {
		t.Fatalf("missing leaf below escaping symlink = %v", err)
	}
	dangling := filepath.Join(root, "dangling")
	if err := os.Symlink(filepath.Join(outside, "absent"), dangling); err != nil {
		t.Fatal(err)
	}
	if _, err := containedPath(root, dangling); err == nil {
		t.Fatal("dangling symlink accepted")
	}
}

