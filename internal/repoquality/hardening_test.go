func TestImageDimensionsRejectSpoofsAndOverflow(t *testing.T) {
	root := t.TempDir()
	pngHeader := make([]byte, 24)
	copy(pngHeader[1:4], "PNG")
	binary.BigEndian.PutUint32(pngHeader[16:20], 10)
	binary.BigEndian.PutUint32(pngHeader[20:24], 20)
	path := filepath.Join(root, "spoof.png")
	if err := os.WriteFile(path, pngHeader, 0o644); err != nil {
		t.Fatal(err)
	}
	if _, _, err := assetDimensions(path); err == nil {
		t.Fatal("PNG substring spoof accepted")
	}
	path = filepath.Join(root, "image.svg")
	for _, content := range []string{
		`<svg width="18446744073709551617" height="1"/>`,
		`<svg width="0" height="1"/>`,
		`<!-- <svg width="10" height="20"/> --><svg/>`,
		`<wrapper><svg width="10" height="20"/></wrapper>`,
	} {
		writeFile(t, path, content)
		if _, _, err := assetDimensions(path); err == nil {
			t.Fatalf("invalid SVG dimensions accepted: %s", content)
		}
	}
	writeFile(t, path, `<svg width='10' height='20'/>`)
	if width, height, err := assetDimensions(path); err != nil || width != 10 || height != 20 {
		t.Fatalf("single-quoted SVG dimensions = %d, %d, %v", width, height, err)
	}
}

func TestWebPDimensionHeadersValidateContainerBounds(t *testing.T) {
	path := filepath.Join(t.TempDir(), "image.webp")
	data := make([]byte, 26)
	copy(data[:4], "RIFF")
	binary.LittleEndian.PutUint32(data[4:8], 18)
	copy(data[8:16], "WEBPVP8L")
	binary.LittleEndian.PutUint32(data[16:20], 5)
	data[20], data[21], data[22], data[23], data[24] = 0x2f, 3, 0x81, 2, 1
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatal(err)
	}
	if width, height, err := assetDimensions(path); err != nil || width != 260 || height != 1035 {
		t.Fatalf("lossless bit fields = %d, %d, %v", width, height, err)
	}
	for _, offset := range []int{4, 16, 24} {
		invalid := bytes.Clone(data)
		invalid[offset] = 0xff
		if err := os.WriteFile(path, invalid, 0o644); err != nil {
			t.Fatal(err)
		}
		if _, _, err := assetDimensions(path); err == nil {
			t.Errorf("invalid WebP field at %d accepted", offset)
		}
	}
}

func mediaFixture(t *testing.T) (string, mediaAsset) {
	t.Helper()
	root := t.TempDir()
	path := filepath.Join(root, "docs", "media", "ok.png")
	writePNG(t, path, 2, 3)
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	digest, err := fileSHA256(path)
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(root, "README.md"), "docs/media/ok.png\n")
	asset := mediaAsset{
		Path: "docs/media/ok.png", Status: "current", Width: 2, Height: 3,
		Bytes: info.Size(), MaxBytes: 10000, SHA256: digest,
		Origin: "project-authored-vector", Alt: "Test image", License: "Apache-2.0",
		RightsStatus: "approved-for-public-repository", RightsBasis: "Test fixture",
		RightsReviewedAt: "2026-09-04", ReviewerRole: "maintainer", SourceRevision: "test-fixture",
		ReplacementHistory: json.RawMessage("[]"), ReferencedBy: []string{"README.md"},
	}
	writeMediaManifest(t, root, asset)
	return root, asset
}

func writeMediaManifest(t *testing.T, root string, asset mediaAsset) {
	t.Helper()
	data, err := json.Marshal(mediaManifest{SchemaVersion: 2, Assets: []mediaAsset{asset}})
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(root, "docs", "media", "manifest.json"), string(data))
}
