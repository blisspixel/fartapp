func TestNPMIntegrityIsCanonicalFullSHA512(t *testing.T) {
	valid := "sha512-" + base64.StdEncoding.EncodeToString(bytes.Repeat([]byte{42}, 64))
	if !validNPMIntegrity(valid) {
		t.Fatal("valid SHA-512 integrity rejected")
	}
	for _, invalid := range []string{"sha512-A", "sha512-AAAA", "sha512-" + strings.Repeat("=", 88), valid + "\n", strings.Replace(valid, "sha512", "sha256", 1)} {
		if validNPMIntegrity(invalid) {
			t.Errorf("invalid integrity %q accepted", invalid)
		}
	}
}

